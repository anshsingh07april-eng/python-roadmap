#Q1. Index practice. Create [5, 12, 8, 20, 3]. Print the first item, the last item, the middle item, and the items at index 1 to 3 using slicing.
my_list = [5, 12, 8, 20, 3]
print("First item:", my_list[0])
print("Last item:", my_list[-1])
print("Middle item:", my_list[len(my_list) // 2])
print("Items at index 1 to 3:", my_list[1:4])